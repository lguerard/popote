const DICTIONNAIRES = { fr, en }

function chercher(dico, key) {
  const valeur = key.split('.').reduce((noeud, part) => (noeud == null ? undefined : noeud[part]), dico)
  return typeof valeur === 'string' ? valeur : undefined
}

// Une clé absente en anglais retombe sur le français, puis sur la clé
// elle-même : un oubli se voit à l'écran sans jamais casser le rendu.
export function translate(lang, key, vars) {
  const texte = chercher(DICTIONNAIRES[lang] || fr, key) ?? chercher(fr, key) ?? key
  if (!vars) return texte
  return texte.replace(/\{(\w+)\}/g, (tout, nom) => (vars[nom] ?? tout))
}
